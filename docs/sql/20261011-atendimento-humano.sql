CREATE TABLE IF NOT EXISTS atendimentos_humanos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barbeiro_id bigint NOT NULL REFERENCES barbeiros(id),
    numero_cliente varchar(255) NOT NULL,
    nome_cliente varchar(255),
    estado varchar(255) NOT NULL CHECK (estado IN ('AUTOMATICO','AGUARDANDO','EM_ATENDIMENTO')),
    responsavel varchar(255), solicitado_em timestamp, ultima_mensagem_cliente_em timestamp,
    erro_aviso text, aviso_mensagem_id varchar(255), aviso_phone_number_id varchar(255),
    CONSTRAINT uk_atendimento_barbeiro_numero UNIQUE (barbeiro_id, numero_cliente)
);
CREATE TABLE IF NOT EXISTS mensagens_atendimento (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atendimento_id bigint NOT NULL REFERENCES atendimentos_humanos(id),
    autor varchar(255) NOT NULL, texto text NOT NULL, criada_em timestamp NOT NULL,
    mensagem_id_meta varchar(255)
);
CREATE INDEX IF NOT EXISTS idx_mensagem_atendimento ON mensagens_atendimento(atendimento_id,id);
